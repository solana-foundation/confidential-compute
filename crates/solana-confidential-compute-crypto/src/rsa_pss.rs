/// Verifies `signature` as RSASSA-PSS SHA-384 over `message` under `modulus`.
///
/// The public exponent is 65537. Salt length is 48. The modulus must be an odd
/// 4096-bit integer.
///
/// @spec SCC-VERIFY-003 SCC-SEC-003
#[inline(never)]
pub(crate) fn verify_rsassa_pss_sha384(
    modulus: &[u8; RSA4096_LEN],
    message: &[u8],
    signature: &[u8],
) -> Result<(), CryptoError> {
    if signature.len() != RSA4096_LEN {
        return Err(CryptoError::MalformedCertificate);
    }
    let mut signature_bytes = [0u8; RSA4096_LEN];
    signature_bytes.copy_from_slice(signature);
    if modulus[0] & 0x80 == 0 || modulus[RSA4096_LEN - 1] & 1 == 0 {
        return Err(CryptoError::MalformedCertificate);
    }
    if signature_bytes.iter().all(|byte| *byte == 0) || signature_bytes >= *modulus {
        return Err(CryptoError::UntrustedRoot);
    }

    let encoded = rsa_public_exp(modulus, &signature_bytes)?;
    pss_sha384_consistent(&encoded, message)
}

fn rsa_public_exp(
    modulus: &[u8; RSA4096_LEN],
    signature: &[u8; RSA4096_LEN],
) -> Result<[u8; RSA4096_LEN], CryptoError> {
    solana_confidential_compute_core::big_mod_exp(signature, &[1, 0, 1], modulus)
        .ok_or(CryptoError::UntrustedRoot)?
        .try_into()
        .map_err(|_| CryptoError::UntrustedRoot)
}

fn pss_sha384_consistent(em: &[u8; RSA4096_LEN], message: &[u8]) -> Result<(), CryptoError> {
    let mut bad = em[RSA4096_LEN - 1] ^ 0xbc;
    let masked_db = &em[..DB_LEN];
    let hash = &em[DB_LEN..DB_LEN + HASH_LEN];
    // emBits = 4095, so the top bit of maskedDB must be clear.
    bad |= masked_db[0] & 0x80;

    let mut db = [0u8; DB_LEN];
    mgf1_sha384(hash, &mut db);
    for (slot, masked) in db.iter_mut().zip(masked_db.iter()) {
        *slot ^= *masked;
    }
    db[0] &= 0x7f;

    for (index, byte) in db.iter().enumerate() {
        if index < PAD_LEN {
            bad |= *byte;
        } else if index == PAD_LEN {
            bad |= *byte ^ 0x01;
        }
    }

    let salt = &db[PAD_LEN + 1..];
    let message_hash = sha384(message);
    let mut primed = Sha384::new();
    primed.update([0u8; 8]);
    primed.update(message_hash);
    primed.update(salt);
    let prime = primed.finalize();
    for (got, expected) in prime.iter().zip(hash.iter()) {
        bad |= got ^ expected;
    }
    if bad == 0 {
        Ok(())
    } else {
        Err(CryptoError::UntrustedRoot)
    }
}

fn mgf1_sha384(seed: &[u8], out: &mut [u8; DB_LEN]) {
    let mut offset = 0;
    let mut counter = 0u32;
    while offset < DB_LEN {
        let mut hasher = Sha384::new();
        hasher.update(seed);
        hasher.update(counter.to_be_bytes());
        let block = hasher.finalize();
        let take = (DB_LEN - offset).min(HASH_LEN);
        out[offset..offset + take].copy_from_slice(&block[..take]);
        offset += take;
        counter = counter.wrapping_add(1);
    }
}

fn sha384(data: &[u8]) -> [u8; HASH_LEN] {
    let mut hasher = Sha384::new();
    hasher.update(data);
    hasher.finalize().into()
}
